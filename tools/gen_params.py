#!/usr/bin/env python3
"""Generate core/ParamData.cpp from data/mx300params.json (the single source of truth).

  python3 tools/gen_params.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "../data/mx300params.json")
OUT = os.path.join(HERE, "../core/ParamData.cpp")

j = json.load(open(SRC))


def h(s):
    return int(s, 16)


def q(s):
    return json.dumps(s, ensure_ascii=False)


KINDS = {"int": "Int", "linear": "Linear", "choice": "Choice", "map": "Map", "table": "Table", "ms": "Ms",
         "rt60": "Rt60", "delay_time": "DelayTime", "feedback": "Feedback", "lfo_hz": "LfoHz", "pan": "Pan",
         "attack": "Attack", "type": "Type", "routing": "Routing"}
table_names = list(j["tables"])

lines = ["// Generated by tools/gen_params.py from data/mx300params.json. Do not edit.",
         '#include "ParamModel.h"', "", "#include <limits>", "", "namespace mx300::data", "{",
         "static constexpr double kNone = std::numeric_limits<double>::quiet_NaN();", ""]

lines.append("extern const std::vector<TypeInfo> kTypes;\nconst std::vector<TypeInfo> kTypes = {")
for t in j["types"]:
    dna = "Dna::Whole" if t["dna"] == "whole" else "Dna::Half"
    k = {"reverb": "Klass::Reverb", "delay": "Klass::Delay", "modulation": "Klass::Modulation"}[t["class"]]
    ps = ", ".join(f"0x{h(p):04X}" for p in t["params"])
    lines.append(f"    {{ 0x{h(t['id']):04X}, {q(t['name'])}, {dna}, {k}, {{ {ps} }} }},")
lines.append("};\n")

for k in ("half", "whole"):
    ids = ", ".join(f"0x{h(x):04X}" for x in j["type_order"][k])
    lines.append(f"extern const std::vector<uint16_t> kOrder{k.capitalize()};\nconst std::vector<uint16_t> kOrder{k.capitalize()} = {{ {ids} }};")
lines.append("")

lines.append("extern const std::vector<ParamInfo> kParams;\nconst std::vector<ParamInfo> kParams = {")
for pid, p in j["params"].items():
    d = p["display"]
    f = [f"DisplayKind::{KINDS[d['kind']]}"]
    f.append(q(d.get("unit", "")))
    f.append(q(d.get("prefix", "")))
    f.append(repr(float(d.get("scale", 1))))
    f.append(repr(float(d.get("offset", 0))))
    f.append(str(d.get("decimals", 0)))
    f.append(str(table_names.index(d["table"]) if "table" in d else -1))
    f.append("{ " + ", ".join(q(c) for c in d.get("choices", [])) + " }")
    f.append("{ " + ", ".join(f"{{ {int(k)}, {q(v)} }}" for k, v in d.get("values", {}).items()) + " }")
    f.append("true" if d.get("tempo") else "false")
    f.append("true" if d.get("zero_is_stop") else "false")
    lo, hi = p.get("min", 0), p.get("max", 0)
    lines.append(f"    {{ 0x{h(pid):04X}, {q(p['name'])}, {lo}, {hi}, {{ {', '.join(f)} }} }},")
lines.append("};\n")

lines.append("extern const std::vector<Table> kTables;\nconst std::vector<Table> kTables = {")
for name, t in j["tables"].items():
    vals, ratios = [], []
    for v in t["values"]:
        if isinstance(v, list):
            ratios.append(f"{{ {v[0]}, {v[1]} }}")
        else:
            vals.append("kNone" if v is None else repr(float(v)))
    lines.append(f"    {{ {q(name)}, {q(t['unit'])}, {{ {', '.join(vals)} }}, {{ {', '.join(ratios)} }} }},")
lines.append("};\n")

rt = j["rt60"]
fmt = lambda rows: ", ".join("{ " + ", ".join(repr(float(x)) for x in r) + " }" for r in rows)
lines.append("extern const std::vector<std::array<double, 3>> kRtHalf, kRtWhole;\nextern const std::vector<std::vector<double>> kRtWholeSizes;\nextern const double kRtK, kRtSampleRate, kRtScale;\nextern const std::vector<std::pair<uint16_t, const char*>> kRoutings;\nextern const std::vector<uint16_t> kWholeRoutings;")
lines.append(f"const std::vector<std::array<double, 3>> kRtHalf = {{ {fmt(rt['half'])} }};")
lines.append(f"const std::vector<std::array<double, 3>> kRtWhole = {{ {fmt(rt['whole'])} }};")
sizes = ", ".join("{ " + ", ".join(repr(float(x)) for x in (r or [])) + " }" for r in rt["whole_size_m"])
lines.append(f"const std::vector<std::vector<double>> kRtWholeSizes = {{ {sizes} }};")
lines.append(f"const double kRtK = {rt['k']}, kRtSampleRate = {rt['sample_rate']}, kRtScale = {rt['scale']};")
lines.append("")
lines.append("const std::vector<std::pair<uint16_t, const char*>> kRoutings = {")
for k, v in j["routing"]["values"].items():
    lines.append(f"    {{ 0x{h(k):04X}, {q(v)} }},")
lines.append("};")
lines.append("const std::vector<uint16_t> kWholeRoutings = { " + ", ".join(f"0x{h(x):04X}" for x in j["routing"]["whole"]) + " };")
lines.append("} // namespace mx300::data\n")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines))
print(f"wrote {os.path.relpath(OUT)}: {len(j['types'])} types, {len(j['params'])} params")
